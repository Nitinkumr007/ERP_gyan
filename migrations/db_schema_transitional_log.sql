-- 1. Create the Master Log Table
-- This table will store all historical changes (Transitional Data)
-- Now enhanced with specific user metadata, transaction IDs, and change diffs.
CREATE TABLE public.system_transitional_log (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,           -- Name of the table being modified
    record_id TEXT,                     -- ID of the record
    operation_type TEXT NOT NULL,       -- 'INSERT', 'UPDATE', 'DELETE'
    
    -- Snapshot Data
    old_record JSONB,                   -- Previous state
    new_record JSONB,                   -- New state
    changes_diff JSONB,                 -- Computed JSON diff (only changed fields)
    
    -- Metadata
    changed_by TEXT,                    -- Auth User ID (UUID)
    user_email TEXT,                    -- Snapshot of email at time of change
    user_role TEXT,                     -- Snapshot of role at time of change
    
    transaction_id BIGINT DEFAULT txid_current(), -- Groups atomic operations together
    changed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    client_info JSONB                   -- IP, User Agent (if provided via app context)
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.system_transitional_log ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow read access to Admins only
CREATE POLICY "Admins can view audit logs"
ON public.system_transitional_log
FOR SELECT
USING (
  auth.uid() IN (
    SELECT id FROM auth.users 
    WHERE raw_user_meta_data->>'role' = 'Admin'
  )
);

